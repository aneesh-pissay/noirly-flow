import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { randomUUID } from "node:crypto";
import {
  CopyObjectCommand,
  DeleteObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";

/**
 * Where task attachments live. Cloudflare R2 when configured — the same
 * R2_* settings as Pulse, Ledger and Split. Files are written privately and
 * only ever served through Flow's own authorised download route, never by a
 * public bucket URL.
 *
 * Without R2, development keeps files in ./.attachments so the feature can be
 * used locally. Production refuses — a server's local disk is not durable —
 * unless ATTACHMENTS_LOCAL_DIR names a folder explicitly (a mounted volume, or
 * the end-to-end tests).
 */

export type StoredObject = { storage: "r2" | "local"; key: string };

let client: S3Client | null = null;

function r2Config() {
  const accountId = process.env.R2_ACCOUNT_ID?.trim();
  const accessKeyId = process.env.R2_ACCESS_KEY_ID?.trim();
  const secretAccessKey = process.env.R2_SECRET_ACCESS_KEY?.trim();
  const bucket = process.env.R2_BUCKET_NAME?.trim();
  if (!accountId || !accessKeyId || !secretAccessKey || !bucket) return null;
  return { accountId, accessKeyId, secretAccessKey, bucket };
}

function r2() {
  const config = r2Config();
  if (!config) throw new Error("R2 is not configured");
  client ??= new S3Client({
    region: "auto",
    endpoint: `https://${config.accountId}.r2.cloudflarestorage.com`,
    credentials: { accessKeyId: config.accessKeyId, secretAccessKey: config.secretAccessKey },
    requestChecksumCalculation: "WHEN_REQUIRED",
    responseChecksumValidation: "WHEN_REQUIRED",
  });
  return { client, bucket: config.bucket };
}

export function canWriteToR2() {
  return Boolean(r2Config());
}

/** Issue a five-minute, content-type-bound URL for a browser to PUT directly to R2. */
export async function createAttachmentUploadUrl(workspaceId: string, taskId: string, contentType: string) {
  if (!r2Config()) return null;
  const { client: s3, bucket } = r2();
  const key = `flow/attachment-uploads/${workspaceId}/${taskId}/${Date.now()}-${randomUUID()}`;
  const uploadUrl = await getSignedUrl(
    s3,
    new PutObjectCommand({ Bucket: bucket, Key: key, ContentType: contentType }),
    { expiresIn: 300, signableHeaders: new Set(["content-type"]) },
  );
  return { key, uploadUrl, contentType };
}

export async function inspectR2Attachment(key: string) {
  const { client: s3, bucket } = r2();
  const result = await s3.send(new HeadObjectCommand({ Bucket: bucket, Key: key }));
  return { size: result.ContentLength ?? 0, contentType: result.ContentType ?? "application/octet-stream" };
}

/** Move a validated temporary upload under the permanent attachment prefix. */
export async function commitR2Attachment(workspaceId: string, sourceKey: string, contentType: string): Promise<StoredObject> {
  const { client: s3, bucket } = r2();
  const key = `flow/attachments/${workspaceId}/${randomUUID()}`;
  const copySource = `/${bucket}/${sourceKey.split("/").map(encodeURIComponent).join("/")}`;
  await s3.send(new CopyObjectCommand({
    Bucket: bucket, Key: key, CopySource: copySource,
    ContentType: contentType, MetadataDirective: "REPLACE",
  }));
  try {
    await s3.send(new DeleteObjectCommand({ Bucket: bucket, Key: sourceKey }));
  } catch {
    await s3.send(new DeleteObjectCommand({ Bucket: bucket, Key: key })).catch(() => {});
    throw new Error("Temporary attachment cleanup failed");
  }
  return { storage: "r2", key };
}

function localDir() {
  return process.env.ATTACHMENTS_LOCAL_DIR || path.join(process.cwd(), ".attachments");
}

/** Local keys are generated by us, but never let one escape the folder. */
function localPath(key: string) {
  const dir = path.resolve(localDir());
  const full = path.resolve(dir, key);
  if (!full.startsWith(dir + path.sep)) throw new Error("Invalid attachment key");
  return full;
}

function localAllowed() {
  return process.env.NODE_ENV !== "production" || Boolean(process.env.ATTACHMENTS_LOCAL_DIR);
}

export async function putAttachment(
  workspaceId: string,
  body: Buffer,
  contentType: string,
): Promise<StoredObject> {
  // Random, not derived from the filename: the name is metadata, the key is not guessable.
  const key = `flow/attachments/${workspaceId}/${randomUUID()}`;
  if (r2Config()) {
    const { client: s3, bucket } = r2();
    await s3.send(new PutObjectCommand({ Bucket: bucket, Key: key, Body: body, ContentType: contentType }));
    return { storage: "r2", key };
  }
  if (!localAllowed()) {
    throw new Error("Attachment storage is not configured: set the R2_* variables.");
  }
  const file = localPath(key);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, body);
  return { storage: "local", key };
}

export async function readAttachment(object: StoredObject): Promise<Uint8Array> {
  if (object.storage === "r2") {
    const { client: s3, bucket } = r2();
    const result = await s3.send(new GetObjectCommand({ Bucket: bucket, Key: object.key }));
    if (!result.Body) throw new Error("Attachment body missing");
    return result.Body.transformToByteArray();
  }
  return readFile(localPath(object.key));
}

/** Best effort: a missing object is already gone. */
export async function removeAttachment(object: StoredObject): Promise<void> {
  try {
    if (object.storage === "r2") {
      if (!r2Config()) return;
      const { client: s3, bucket } = r2();
      await s3.send(new DeleteObjectCommand({ Bucket: bucket, Key: object.key }));
      return;
    }
    await rm(localPath(object.key), { force: true });
  } catch {
    console.error("attachment delete failed");
  }
}
